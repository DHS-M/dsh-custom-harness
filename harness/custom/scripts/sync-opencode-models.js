#!/usr/bin/env node
/**
 * Sync llm-opencode model list from OpenCode Zen GET /v1/models.
 *
 * Underlying bug: settings.yaml listed only one (or a few) models, so the Web UI
 * model picker only showed those. DSH pi-ai custom providers use the static
 * `models:` array — they do not auto-discover /v1/models at runtime.
 *
 * Keyless: Authorization Bearer public + OpenCode client headers (same as CLI).
 */
const fs = require("fs");
const path = require("path");

const BASE = process.env.OPENCODE_BASE_URL || "https://opencode.ai/zen/v1";
const KEY = process.env.OPENCODE_PUBLIC_KEY || process.env.OPENCODE_API_KEY || "public";
const HOME = process.env.DSH_HOME || path.join(process.env.HOME || "/tmp", ".dsh");
const SETTINGS = path.join(HOME, "settings.yaml");
const CACHE = path.join(HOME, "opencode-models.json");

async function fetchModels() {
  const res = await fetch(`${BASE.replace(/\/$/, "")}/models`, {
    headers: {
      Authorization: `Bearer ${KEY}`,
      "User-Agent": process.env.OPENCODE_USER_AGENT || "opencode/1.15.5",
      "x-opencode-client": "cli",
      "x-opencode-project": process.env.OPENCODE_PROJECT || "dsh-m",
    },
    signal: AbortSignal.timeout(20000),
  });
  if (!res.ok) {
    throw new Error(`OpenCode /models HTTP ${res.status}: ${(await res.text()).slice(0, 300)}`);
  }
  const body = await res.json();
  const data = Array.isArray(body?.data) ? body.data : Array.isArray(body) ? body : [];
  const ids = [...new Set(data.map((m) => m.id || m.name).filter(Boolean))];
  if (!ids.length) throw new Error("OpenCode /models returned zero models");
  return ids;
}

function modelsYamlBlock(ids) {
  return ids
    .map((id) => {
      const name = id
        .replace(/-/g, " ")
        .replace(/\b\w/g, (c) => c.toUpperCase());
      return `        - id: ${JSON.stringify(id)}\n          name: ${JSON.stringify(name)}\n          contextWindow: 200000\n          maxTokens: 128000`;
    })
    .join("\n");
}

function buildSettings(ids) {
  const defaultModel =
    ids.includes("big-pickle") ? "big-pickle"
    : ids.find((id) => id.endsWith("-free")) || ids[0];

  return `# Generated by sync-opencode-models.js — do not hand-edit models list
# Source: ${BASE}/models (count=${ids.length})
llm-pi-ai:
  providers:
    llm-opencode:
      displayName: OpenCode (Zen)
      apiKeyEnv: OPENCODE_PUBLIC_KEY
      api: openai-completions
      baseURL: ${BASE}
      headers:
        User-Agent: opencode/1.15.5
        x-opencode-client: cli
        x-opencode-project: dsh-m
      models:
${modelsYamlBlock(ids)}
agent-default-model:
  provider: llm-opencode
  model: ${JSON.stringify(defaultModel)}
`;
}

function mergeOrWrite(ids) {
  fs.mkdirSync(HOME, { recursive: true });
  fs.writeFileSync(CACHE, JSON.stringify({ fetchedAt: new Date().toISOString(), count: ids.length, ids }, null, 2));

  const next = buildSettings(ids);
  if (!fs.existsSync(SETTINGS)) {
    fs.writeFileSync(SETTINGS, next);
    console.log("[sync-opencode-models] wrote new", SETTINGS, "models=", ids.length);
    return;
  }

  let cur = fs.readFileSync(SETTINGS, "utf8");
  // Replace entire llm-opencode models list + provider block if present; else append
  if (/llm-opencode:\s*\n/.test(cur) && /providers:\s*\n/.test(cur)) {
    // Nuclear but reliable: rewrite llm-pi-ai section if we own it, else write sidecar and full replace of models under llm-opencode
    const re =
      /(llm-opencode:\s*\n(?:[ \t]+.*\n)*?)([ \t]+models:\s*\n(?:[ \t]+- id:.*\n(?:[ \t]+.*\n)*)*)/;
    if (re.test(cur)) {
      cur = cur.replace(re, (match, head) => {
        // rebuild llm-opencode provider head + full models
        return (
          `    llm-opencode:\n` +
          `      displayName: OpenCode (Zen)\n` +
          `      apiKeyEnv: OPENCODE_PUBLIC_KEY\n` +
          `      api: openai-completions\n` +
          `      baseURL: ${BASE}\n` +
          `      headers:\n` +
          `        User-Agent: opencode/1.15.5\n` +
          `        x-opencode-client: cli\n` +
          `        x-opencode-project: dsh-m\n` +
          `      models:\n` +
          modelsYamlBlock(ids) +
          `\n`
        );
      });
      // ensure agent-default-model exists
      if (!/agent-default-model:/.test(cur)) {
        const def = ids.includes("big-pickle") ? "big-pickle" : ids[0];
        cur +=
          `\nagent-default-model:\n  provider: llm-opencode\n  model: ${JSON.stringify(def)}\n`;
      }
      fs.writeFileSync(SETTINGS, cur);
      console.log("[sync-opencode-models] updated models in", SETTINGS, "models=", ids.length);
      return;
    }
  }

  fs.writeFileSync(SETTINGS, next);
  console.log("[sync-opencode-models] replaced", SETTINGS, "models=", ids.length);
}

(async () => {
  try {
    const ids = await fetchModels();
    mergeOrWrite(ids);
  } catch (e) {
    console.error("[sync-opencode-models] failed:", e.message || e);
    process.exitCode = 1;
  }
})();
